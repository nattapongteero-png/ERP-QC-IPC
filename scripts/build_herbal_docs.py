def measure(draw, text, font):
    b = draw.textbbox((0,0), text, font=font)
    return b[2]-b[0], b[3]-b[1]

def center_text(draw, cx, cy, text, font, fill="#000", line_gap=4):
    lines = text.split("\n")
    hs = [measure(draw, ln, font)[1] for ln in lines]
    total = sum(hs) + line_gap*(len(lines)-1)
    y = cy - total/2
    for ln, h in zip(lines, hs):
        w,_ = measure(draw, ln, font)
        draw.text((cx-w/2, y), ln, font=font, fill=fill)
        y += h + line_gap

def box(draw, x, y, w, h, text, fill, font, tcol="#ffffff", outline=None, r=14):
    draw.rounded_rectangle([x,y,x+w,y+h], radius=r, fill=fill,
                           outline=outline or fill, width=2)
    center_text(draw, x+w/2, y+h/2, text, font, tcol)

def arrow(draw, x1, y1, x2, y2, col=SLATE, w=4, head=11):
    draw.line([x1,y1,x2,y2], fill=col, width=w)
    import math
    ang = math.atan2(y2-y1, x2-x1)
    for s in (math.pi*0.85, -math.pi*0.85):
        draw.line([x2, y2, x2+head*math.cos(ang+s), y2+head*math.sin(ang+s)],
                  fill=col, width=w)

